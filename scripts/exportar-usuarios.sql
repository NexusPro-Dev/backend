-- Genera db/dev-seed/semilla-usuarios.sql con las personas de la base local que
-- NO son de semilla-desarrollo.sql —los agentes creados desde afftrack y las
-- cuentas dadas de alta por la API—, sus roles, superiores y membresías, y
-- TODAS las cuentas de broker. Se corre a mano, contra la base del compose, y
-- su salida ES el guion de la semilla:
--
--   docker cp scripts/exportar-usuarios.sql nexus-db:/tmp/exportar.sql; docker exec nexus-db sh -c "psql -U nexus -d nexus -At -q -f /tmp/exportar.sql > /tmp/semilla.sql"; docker cp nexus-db:/tmp/semilla.sql src/main/resources/db/dev-seed/semilla-usuarios.sql
--
-- ANONIMIZA lo que identifica a una persona real: el guion va a git y corre en
-- testing, que es público. Correo <usuario>@factech.co, la contraseña del
-- superadministrador sin cambio obligatorio, documento CC derivado del usuario y
-- teléfono derivado, como las diecinueve; sin dirección. No copia ningún hash.
--
-- Volver a correrlo reemplaza la semilla con lo que haya en la base ese día.

\set semilla '''^(superadmin|(admin|manager|director|agente|cliente)[0-9]+)$'''

WITH personas AS (
  SELECT u.*, c.code AS pais
    FROM users u LEFT JOIN countries c ON c.id = u.country_id
   WHERE u.username !~ :semilla AND u.deleted_at IS NULL
)
SELECT concat_ws(E'\n',
'-- =============================================================================',
'-- Semilla de DESARROLLO: las personas de la base local que no son de',
'-- semilla-desarrollo.sql, con sus roles, superiores y membresías, y todas las',
'-- cuentas de broker (vendedor y consumidor, con su origen).',
'--',
'-- Generada con scripts/exportar-usuarios.sql el ' || to_char(now(), 'DD-MM-YYYY') || ': '
  || (SELECT count(*) FROM personas) || ' personas y ' || (SELECT count(*) FROM user_brokers) || ' cuentas de broker.',
'--',
'-- LA APLICA `DevelopmentDataSeeder` AL ARRANCAR, la última, y bajo las mismas',
'-- condiciones que las demás: nunca en `production`. Va después de',
'-- semilla-desarrollo.sql —los superiores y la contraseña son de allí— y de',
'-- semilla-productos.sql —las membresías se resuelven por código de producto—.',
'--',
'-- ANONIMIZADA: correo <usuario>@factech.co, contraseña del superadministrador',
'-- sin cambio obligatorio, documento CC y teléfono derivados del usuario, sin',
'-- dirección. Los nombres y el estado son los de la base local.',
'--',
'-- ES REPETIBLE: una persona que ya existe (por usuario o identificador) no se',
'-- toca, y sus roles, superiores y membresías solo se escriben al crearla. Una',
'-- cuenta de broker que ya existe (por identificador o por broker y número) se',
'-- salta; el origen solo se pone si la cuenta de origen está.',
'--',
'-- La línea USUARIOS la lee DevelopmentSeedIT para limpiar lo que sembró.',
'-- =============================================================================',
'-- USUARIOS: ' || (SELECT string_agg(username, ',' ORDER BY username) FROM personas),
'',
'CREATE TEMP TABLE semilla_usuarios_nuevos (id uuid PRIMARY KEY) ON COMMIT DROP;',
'',
'WITH v (id, username, first_name, last_name, status, pais, city, created_at) AS (VALUES',
(SELECT string_agg(format('    (%L::uuid, %L, %L, %L, %L, %L, %L, %L::timestamptz)',
                          id, username, first_name, last_name, status, pais, city, created_at),
                   E',\n' ORDER BY created_at, id) FROM personas),
'), nuevas AS (',
'  INSERT INTO users (id, username, email, first_name, last_name, password_hash,',
'                     must_change_password, status, country_id, document_type_id,',
'                     document_number, phone, city, created_at, updated_at)',
'  SELECT v.id, v.username, lower(v.username) || ''@factech.co'', v.first_name, v.last_name,',
'         (SELECT password_hash FROM users WHERE username = ''superadmin''), false, v.status,',
'         (SELECT c.id FROM countries c WHERE c.code = v.pais),',
'         (SELECT d.id FROM document_types d WHERE d.abbreviation = ''CC''),',
'         upper(regexp_replace(v.username, ''[^A-Za-z0-9]'', '''', ''g'')),',
'         ''+57300'' || lpad((abs(hashtext(v.username)) % 10000000)::text, 7, ''0''),',
'         v.city, v.created_at, v.created_at',
'    FROM v',
'   WHERE NOT EXISTS (SELECT 1 FROM users u',
'                      WHERE lower(u.username) = lower(v.username) OR u.id = v.id)',
'  RETURNING id',
')',
'INSERT INTO semilla_usuarios_nuevos SELECT id FROM nuevas;',
'',
'INSERT INTO user_roles (user_id, role_id, role_type)',
'SELECT u.id, r.id, r.role_type',
'  FROM (VALUES',
(SELECT string_agg(format('    (%L, %L)', p.username, r.code), E',\n' ORDER BY p.username, r.code)
   FROM personas p JOIN user_roles ur ON ur.user_id = p.id JOIN roles r ON r.id = ur.role_id),
'       ) AS v (username, rol)',
'  JOIN users u ON u.username = v.username',
'  JOIN semilla_usuarios_nuevos n ON n.id = u.id',
'  JOIN roles r ON r.code = v.rol',
'ON CONFLICT DO NOTHING;',
'',
coalesce((SELECT concat_ws(E'\n',
'INSERT INTO user_supervisors (id, user_id, supervisor_id, started_at, ended_at)',
'SELECT v.id, u.id, s.id, v.started_at, v.ended_at',
'  FROM (VALUES',
string_agg(format('    (%L::uuid, %L, %L, %L::timestamptz, %L::timestamptz)',
                  us.id, p.username, s.username, us.started_at, us.ended_at),
           E',\n' ORDER BY p.username, us.started_at),
'       ) AS v (id, username, superior, started_at, ended_at)',
'  JOIN users u ON u.username = v.username',
'  JOIN semilla_usuarios_nuevos n ON n.id = u.id',
'  JOIN users s ON s.username = v.superior',
'ON CONFLICT DO NOTHING;',
'')
   FROM personas p JOIN user_supervisors us ON us.user_id = p.id
   JOIN users s ON s.id = us.supervisor_id), ''),
coalesce((SELECT concat_ws(E'\n',
'INSERT INTO user_products (id, user_id, membership_id, product_id, started_at, ends_at,',
'                           closed_at, validity_days)',
'SELECT v.id, u.id, v.membership_id, pr.id, v.started_at, v.ends_at, v.closed_at,',
'       v.validity_days',
'  FROM (VALUES',
string_agg(format('    (%L::uuid, %L, %L::uuid, %L, %L::timestamptz, %L::timestamptz, %L::timestamptz, %L::integer)',
                  up.id, p.username, up.membership_id, pr.code, up.started_at, up.ends_at,
                  up.closed_at, up.validity_days),
           E',\n' ORDER BY p.username, up.started_at),
'       ) AS v (id, username, membership_id, producto, started_at, ends_at, closed_at,',
'               validity_days)',
'  JOIN users u ON u.username = v.username',
'  JOIN semilla_usuarios_nuevos n ON n.id = u.id',
'  LEFT JOIN products pr ON pr.code = v.producto',
' WHERE v.membership_id IS NULL OR EXISTS (SELECT 1 FROM memberships m WHERE m.id = v.membership_id)',
'ON CONFLICT DO NOTHING;',
'')
   FROM personas p JOIN user_products up ON up.user_id = p.id
   LEFT JOIN products pr ON pr.id = up.product_id), ''),
'-- Las cuentas de broker: primero las de vendedor, que son el origen de las de',
'-- consumidor. El titular se resuelve por usuario; una cuenta cuyo titular no',
'-- existe se salta.',
(SELECT concat_ws(E'\n',
'CREATE TEMP TABLE semilla_cuentas ON COMMIT DROP AS',
'SELECT * FROM (VALUES',
string_agg(format('    (%L::uuid, %L, %L::uuid, %L, %L, %L, %L, %L::uuid, %L::timestamptz, %L::integer, %L::timestamptz, %L::timestamptz, %L::timestamptz, %L, %L::bigint, %L::bigint, %L, %L::timestamptz, %L::timestamptz)',
                  ub.id, u.username, ub.broker_id, ub.external_id, ub.status, ub.kind, ub.afftrack,
                  ub.referrer_account_id, ub.first_deposit_at, ub.operations_count,
                  ub.first_operation_at, ub.last_operation_at, ub.registered_at, ub.country_code,
                  ub.first_deposit_amount, ub.deposits_total, ub.deposit_currency, ub.created_at,
                  ub.updated_at),
           E',\n' ORDER BY ub.kind DESC, ub.created_at, ub.id),
'       ) AS v (id, username, broker_id, external_id, status, kind, afftrack, referrer_account_id,',
'               first_deposit_at, operations_count, first_operation_at, last_operation_at,',
'               registered_at, country_code, first_deposit_amount, deposits_total,',
'               deposit_currency, created_at, updated_at);',
'')
   FROM user_brokers ub LEFT JOIN users u ON u.id = ub.user_id),
'INSERT INTO user_brokers (id, user_id, broker_id, external_id, status, kind, afftrack,',
'                          referrer_account_id, first_deposit_at, operations_count,',
'                          first_operation_at, last_operation_at, registered_at, country_code,',
'                          first_deposit_amount, deposits_total, deposit_currency, created_at,',
'                          updated_at)',
'SELECT v.id, u.id, v.broker_id, v.external_id, v.status, v.kind, v.afftrack,',
'       CASE WHEN EXISTS (SELECT 1 FROM user_brokers o',
'                          WHERE o.id = v.referrer_account_id AND o.broker_id = v.broker_id)',
'            THEN v.referrer_account_id END,',
'       v.first_deposit_at, v.operations_count, v.first_operation_at, v.last_operation_at,',
'       v.registered_at, v.country_code, v.first_deposit_amount, v.deposits_total,',
'       v.deposit_currency, v.created_at, v.updated_at',
'  FROM semilla_cuentas v',
'  JOIN brokers b ON b.id = v.broker_id',
'  LEFT JOIN users u ON u.username = v.username',
' WHERE v.kind = ''VENDEDOR'' AND u.id IS NOT NULL',
'ON CONFLICT DO NOTHING;',
'',
'INSERT INTO user_brokers (id, user_id, broker_id, external_id, status, kind, afftrack,',
'                          referrer_account_id, first_deposit_at, operations_count,',
'                          first_operation_at, last_operation_at, registered_at, country_code,',
'                          first_deposit_amount, deposits_total, deposit_currency, created_at,',
'                          updated_at)',
'SELECT v.id, u.id, v.broker_id, v.external_id, v.status, v.kind, v.afftrack,',
'       CASE WHEN EXISTS (SELECT 1 FROM user_brokers o',
'                          WHERE o.id = v.referrer_account_id AND o.broker_id = v.broker_id)',
'            THEN v.referrer_account_id END,',
'       v.first_deposit_at, v.operations_count, v.first_operation_at, v.last_operation_at,',
'       v.registered_at, v.country_code, v.first_deposit_amount, v.deposits_total,',
'       v.deposit_currency, v.created_at, v.updated_at',
'  FROM semilla_cuentas v',
'  JOIN brokers b ON b.id = v.broker_id',
'  LEFT JOIN users u ON u.username = v.username',
' WHERE v.kind = ''CONSUMIDOR'' AND (v.username IS NULL OR u.id IS NOT NULL)',
'ON CONFLICT DO NOTHING;',
'')
FROM (SELECT 1) AS una;
